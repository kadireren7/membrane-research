#!/usr/bin/env python3
"""Generate every table paper/main.md/main.tex references, from real
committed CSV artifacts (plus paper/related-work-matrix.md for the
related-work table) -- no hand-typed numbers. Output: paper/tables/*.md.

Usage: paper/scripts/generate-tables.py [--check]
"""
import csv
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
BENCH = REPO_ROOT / "benchmarks" / "cxl-sim"
TABLES_DIR = REPO_ROOT / "paper" / "tables"

HOST_8GIB = "8589934592"
DEV_2TIB = "2199023255552"


def read_rows(path):
	with open(path, newline="") as f:
		return list(csv.DictReader(f))


def table_major_results():
	rows = read_rows(BENCH / "unified-sweep.csv")
	baseline_full = {r["model"]: float(r["mean_bytes_per_token"]) for r in rows if r["comparison"] == "full-scan-cxl"}
	lines = [
		"# Major results (representative point: 8GiB host / 2TiB device / all-Q8)",
		"",
		"Regenerated from `benchmarks/cxl-sim/unified-sweep.csv` by",
		"`paper/scripts/generate-tables.py` -- do not hand-edit.",
		"",
		"| Model | Comparison | Mean bytes/token | Reduction vs. full-scan-CXL | Hit rate | Precision/Recall |",
		"|---|---|---|---|---|---|",
	]
	for m in ["SmolLM2-135M", "SmolLM2-360M"]:
		for comp in ["exact-no-prefetch", "exact-predictor", "exact-predictor-prefetch",
				"exact-predictor-coalescing", "oracle"]:
			match = [r for r in rows if r["model"] == m and r["comparison"] == comp
				and r["precision"] == "all-q8" and r["host_cache_total_bytes"] == HOST_8GIB
				and r["device_total_bytes"] == DEV_2TIB]
			if not match:
				continue
			r = match[0]
			bpt = float(r["mean_bytes_per_token"])
			ratio = baseline_full[m] / bpt
			lines.append(
				f"| {m} | {comp} | {bpt:,.1f} | {ratio:.1f}x | "
				f"{float(r['calib_hit_rate']):.4f} | {float(r['calib_precision']):.3f} / {float(r['calib_recall']):.3f} |"
			)
	return "\n".join(lines) + "\n"


