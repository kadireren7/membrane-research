def table_unified_stress_results():
	rows = read_rows(BENCH / "unified-sweep.csv")
	lines = [
		"# Unified stress results (scenario completion)",
		"",
		"Regenerated from `benchmarks/cxl-sim/unified-sweep.csv` by",
		"`paper/scripts/generate-tables.py`.",
		"",
		"| Model | Total rows | Real (non-analytical) rows | 10ms p99 met | Capacity ratio reaches >=1.0 (any device, all-Q8) |",
		"|---|---|---|---|---|",
	]
	for m in ["SmolLM2-135M", "SmolLM2-360M"]:
		mrows = [r for r in rows if r["model"] == m]
		real_rows = [r for r in mrows if r["comparison"] not in ("full-scan-cxl", "compressed-full-scan-cxl")]
		met_10ms = sum(1 for r in real_rows if float(r["p99_latency_ns"]) <= 10_000_000)
		cap_ge1 = any(
			r["precision"] == "all-q8" and r["cap_effective_capacity_ratio"]
			and float(r["cap_effective_capacity_ratio"]) >= 1.0
			for r in mrows
		)
		lines.append(f"| {m} | {len(mrows)} | {len(real_rows)} | {met_10ms}/{len(real_rows)} | {'yes' if cap_ge1 else 'no'} |")
	lines.append("")
	lines.append(f"**Total: {len(rows)}/462 rows, {sum(1 for r in rows if r['model']=='SmolLM2-135M')+sum(1 for r in rows if r['model']=='SmolLM2-360M')} across both models.**")
	return "\n".join(lines) + "\n"


