def table_related_work_comparison():
	matrix_path = REPO_ROOT / "paper" / "related-work-matrix.md"
	text = matrix_path.read_text()
	m = re.search(r"(\| Work \| Year \|.*?\n)((?:\|.*\n)+)", text)
	if not m:
		raise RuntimeError("could not find the comparison table in related-work-matrix.md")
	header, body = m.group(1), m.group(2)
	condensed_cols = ["Work", "Year", "Exact or approximate", "Real hardware", "Relationship to MEMBRANE"]
	header_cols = [c.strip() for c in header.strip().strip("|").split("|")]
	idx = [header_cols.index(c) for c in condensed_cols]
	out_lines = [
		"# Related-work comparison (condensed)",
		"",
		"Full 12-column matrix: `paper/related-work-matrix.md`. This is a",
		"condensed extract, regenerated by `paper/scripts/generate-tables.py`.",
		"",
		"| " + " | ".join(condensed_cols) + " |",
		"|" + "---|" * len(condensed_cols),
	]
	for line in body.strip().splitlines():
		cols = [c.strip() for c in line.strip().strip("|").split("|")]
		if len(cols) != len(header_cols):
			continue
		if all(re.fullmatch(r"-+", c) for c in cols):
			continue  # markdown header-separator row, not data
		out_lines.append("| " + " | ".join(cols[i] for i in idx) + " |")
	return "\n".join(out_lines) + "\n"


TABLES = {
	"major-results.md": table_major_results,
	"hardware-datapath-verification.md": table_hardware_datapath_verification,
	"unified-stress-results.md": table_unified_stress_results,
	"negative-result-summary.md": table_negative_result_summary,
	"limitations.md": table_limitations,
	"related-work-comparison.md": table_related_work_comparison,
}


def main():
	check_only = "--check" in sys.argv
	generated = {name: fn() for name, fn in TABLES.items()}

	if check_only:
		bad = []
		for name, content in generated.items():
			path = TABLES_DIR / name
			if not path.exists() or path.read_text() != content:
				bad.append(name)
		if bad:
			print(f"generate-tables.py --check: out of date: {bad}", file=sys.stderr)
			return 1
		print("generate-tables.py --check: all tables up to date.")
		return 0

	TABLES_DIR.mkdir(parents=True, exist_ok=True)
	for name, content in generated.items():
		(TABLES_DIR / name).write_text(content)
	print(f"wrote {len(generated)} tables to {TABLES_DIR}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
